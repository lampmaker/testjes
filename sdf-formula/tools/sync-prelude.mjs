#!/usr/bin/env node
//======================================================================================================================
// THE SHAPE LIBRARY, TAKEN FROM SHADYTRACER: writes src/prelude.js -- the WGSL every scene's code can call (sdf.js's
// PRIMITIVES: Nsphere, NboxRounded, g2Revolve, ... and core/shapes.js inside it) -- from a ShadyTracer checkout, so
// the formula is the shader's own arithmetic and not a copy written again by hand.
//
//   node tools/sync-prelude.mjs ../../ShadyTracer
//
// Run it again after ShadyTracer's shapes change; the tests (test/test.mjs) then say whether the formula still agrees
// with ShadyTracer's own JavaScript twins of them.
//======================================================================================================================
import { writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { resolve, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(process.argv[2] || resolve(here, '../../../ShadyTracer'))
const { PRIMITIVES } = await import(pathToFileURL(resolve(root, 'lib/pathtracer/core/sdf.js')).href)
// the scene API too (csgUnion, csgRoundIntersect, ... which code may call); its add_new, fold, warp and the rest the
// interpreter answers itself (src/scene.js), so their bodies here are never run
const { SCENE_API } = await import(pathToFileURL(resolve(root, 'lib/pathtracer/core/scene_api.js')).href)
let revision = 'unknown'
try { revision = execFileSync('git', ['-C', root, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim() } catch { /* not a git checkout */ }

const out = `// GENERATED by tools/sync-prelude.mjs from ShadyTracer ${revision} (lib/pathtracer/core/sdf.js PRIMITIVES, scene_api.js SCENE_API).
// Do not edit: run the tool again.
export const PRELUDE_REVISION = ${JSON.stringify(revision)}
export const PRELUDE = ${JSON.stringify(PRIMITIVES + '\n' + SCENE_API)}
`
writeFileSync(resolve(here, '../src/prelude.js'), out)
console.log(`src/prelude.js: ${PRIMITIVES.length + SCENE_API.length} characters of WGSL from ShadyTracer ${revision}`)
